"""Write `rust/moteval/src/pyfmt/printable.rs`: the code points `str.isprintable` rejects.

Python's `repr(str)` escapes every non-printable character, and printability above
U+00FF comes from the Unicode database of the running interpreter. Run this with the
reference interpreter (CPython 3.14.8, Unicode 16.0.0):

    uv run python rust/scripts/gen_printable.py
"""

import sys
import unicodedata
from pathlib import Path

OUT = Path(__file__).resolve().parents[1] / "moteval" / "src" / "pyfmt" / "printable.rs"


def nonprintable_ranges() -> list[tuple[int, int]]:
    ranges: list[tuple[int, int]] = []
    start = None
    for code in range(0x110000 + 1):
        nonprintable = code < 0x110000 and not chr(code).isprintable()
        if nonprintable and start is None:
            start = code
        elif not nonprintable and start is not None:
            ranges.append((start, code - 1))
            start = None
    return ranges


def main() -> None:
    ranges = nonprintable_ranges()
    lines = [
        "//! Generated by `rust/scripts/gen_printable.py`; do not edit.",
        f"//! CPython {sys.version.split()[0]}, Unicode {unicodedata.unidata_version}.",
        "",
        "/// Inclusive code point ranges for which `str.isprintable()` is false, sorted.",
        "pub const NONPRINTABLE: &[(u32, u32)] = &[",
        *(f"    (0x{lo:04x}, 0x{hi:04x})," for lo, hi in ranges),
        "];",
        "",
    ]
    OUT.write_text("\n".join(lines))
    print(f"wrote {len(ranges)} ranges to {OUT}")


if __name__ == "__main__":
    main()
