import sys
import unicodedata
from pathlib import Path

OUT = Path(__file__).resolve().parents[1] / "src" / "pyfmt" / "printable.rs"


def nonprintable_ranges() -> list[tuple[int, int]]:
    ranges: list[tuple[int, int]] = []
    start = None
    for code in range(0x110000 + 1):
        nonprintable = code < 0x110000 and not chr(code).isprintable()
        if nonprintable and start is None:
            start = code
        elif not nonprintable and start is not None:
            ranges.append((start, code - 1))
            start = None
    return ranges


def main() -> None:
    ranges = nonprintable_ranges()
    lines = [
        "//! Generated by `scripts/gen_printable.py`; do not edit.",
        f"//! CPython {sys.version.split()[0]}, Unicode {unicodedata.unidata_version}.",
        "",
        "/// Inclusive code point ranges for which `str.isprintable()` is false, sorted.",
        "pub const NONPRINTABLE: &[(u32, u32)] = &[",
        *(f"    (0x{lo:04x}, 0x{hi:04x})," for lo, hi in ranges),
        "];",
        "",
    ]
    OUT.write_text("\n".join(lines))
    print(f"wrote {len(ranges)} ranges to {OUT}")


if __name__ == "__main__":
    main()
