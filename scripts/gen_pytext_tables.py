"""Write `src/formats/pytables.rs`: the Unicode tables Python's text parsing uses.

`read_mot` and the loaders parse text the way CPython does. Three character classes come
from the Unicode database of the running interpreter:

- whitespace (`str.isspace`, `str.strip`, `str.split()`, and `re`'s `\\s`);
- line boundaries (`str.splitlines`);
- decimal digits (`int()` and `float()` map every Unicode decimal digit to ASCII).

Run this with the reference interpreter (CPython 3.14.8, Unicode 16.0.0):

    uv run python scripts/gen_pytext_tables.py
"""

import sys
import unicodedata
from pathlib import Path

OUT = Path(__file__).resolve().parents[1] / "src" / "formats" / "pytables.rs"
MAX_CODE = 0x110000


def code_points(predicate) -> list[int]:
    return [code for code in range(MAX_CODE) if predicate(code)]


def is_line_break(code: int) -> bool:
    return len(("a" + chr(code) + "b").splitlines()) == 2


def decimal_ranges() -> list[tuple[int, int, int]]:
    """`(first, last, value of first)` for each run of consecutive decimal digits."""
    ranges: list[tuple[int, int, int]] = []
    for code in range(MAX_CODE):
        ch = chr(code)
        if not ch.isdecimal():
            continue
        value = unicodedata.decimal(ch)
        assert int(ch) == value, hex(code)
        if ranges and ranges[-1][1] == code - 1 and ranges[-1][2] + (code - ranges[-1][0]) == value:
            first, _, first_value = ranges[-1]
            ranges[-1] = (first, code, first_value)
        else:
            ranges.append((code, code, value))
    return ranges


def main() -> None:
    spaces = code_points(lambda c: chr(c).isspace())
    breaks = code_points(is_line_break)
    digits = decimal_ranges()
    lines = [
        "//! Generated by `scripts/gen_pytext_tables.py`; do not edit.",
        f"//! CPython {sys.version.split()[0]}, Unicode {unicodedata.unidata_version}.",
        "",
        "/// Code points for which `str.isspace()` is true, sorted.",
        "pub const SPACE: &[u32] = &[",
        *(f"    0x{c:04x}," for c in spaces),
        "];",
        "",
        "/// Code points `str.splitlines()` splits on (`\\r\\n` also counts as one), sorted.",
        "pub const LINE_BREAK: &[u32] = &[",
        *(f"    0x{c:04x}," for c in breaks),
        "];",
        "",
        "/// `(first, last, value of first)`: runs of consecutive decimal digits, sorted.",
        "pub const DECIMAL: &[(u32, u32, u32)] = &[",
        *(f"    (0x{lo:04x}, 0x{hi:04x}, {v})," for lo, hi, v in digits),
        "];",
        "",
    ]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines))
    print(f"wrote {len(spaces)} spaces, {len(breaks)} line breaks, {len(digits)} digit runs")


if __name__ == "__main__":
    main()
